
-- CIPHERMED
-- Script 01: Creacion de tablas
-- MySQL 8.4

CREATE DATABASE IF NOT EXISTS ciphermed_db
CHARACTER SET utf8mb4
COLLATE utf8mb4_0900_ai_ci;

USE ciphermed_db;

-- 1. USUARIO
CREATE TABLE IF NOT EXISTS Usuario (
    ID_USUARIO INT AUTO_INCREMENT PRIMARY KEY,
    NOMBRE VARCHAR(100) NOT NULL,
    APELLIDO VARCHAR(100) NOT NULL,
    CORREO VARCHAR(150) NOT NULL UNIQUE,
    PASSWORD_HASH VARCHAR(255) NOT NULL,
    TELEFONO VARCHAR(20),
    FECHA_REGISTRO DATETIME DEFAULT CURRENT_TIMESTAMP,
    ESTADO ENUM('ACTIVO', 'INACTIVO', 'BLOQUEADO')
        NOT NULL DEFAULT 'ACTIVO'
) ENGINE=InnoDB;

-- 2. ROL
CREATE TABLE IF NOT EXISTS Rol (
    ID_ROL INT AUTO_INCREMENT PRIMARY KEY,
    NOMBRE_ROL VARCHAR(50) NOT NULL UNIQUE
) ENGINE=InnoDB;

-- 3. USUARIO_ROL
CREATE TABLE IF NOT EXISTS Usuario_Rol (
    ID_USUARIO INT NOT NULL,
    ID_ROL INT NOT NULL,

    PRIMARY KEY (ID_USUARIO, ID_ROL),

    FOREIGN KEY (ID_USUARIO)
        REFERENCES Usuario(ID_USUARIO)
        ON DELETE CASCADE,

    FOREIGN KEY (ID_ROL)
        REFERENCES Rol(ID_ROL)
        ON DELETE RESTRICT
) ENGINE=InnoDB;

-- 4. MEDICO
CREATE TABLE IF NOT EXISTS Medico (
    ID_MEDICO INT AUTO_INCREMENT PRIMARY KEY,
    ID_USUARIO INT NOT NULL UNIQUE,
    ESPECIALIDAD VARCHAR(100),
    NUMERO_LICENCIA VARCHAR(100) NOT NULL UNIQUE,

    FOREIGN KEY (ID_USUARIO)
        REFERENCES Usuario(ID_USUARIO)
        ON DELETE RESTRICT
) ENGINE=InnoDB;

-- 5. HISTORIAL MEDICO
CREATE TABLE IF NOT EXISTS Historial_Medico (
    ID_HISTORIAL INT AUTO_INCREMENT PRIMARY KEY,
    ID_USUARIO INT NOT NULL,
    DESCRIPCION TEXT,
    DIAGNOSTICO TEXT,
    TRATAMIENTO TEXT,
    FECHA_REGISTRO DATETIME DEFAULT CURRENT_TIMESTAMP,

    FOREIGN KEY (ID_USUARIO)
        REFERENCES Usuario(ID_USUARIO)
        ON DELETE RESTRICT
) ENGINE=InnoDB;

-- 6. ACCESO MEDICO
CREATE TABLE IF NOT EXISTS AccesoMedico (
    ID_ACCESO INT AUTO_INCREMENT PRIMARY KEY,
    ID_USUARIO INT NOT NULL,
    ID_MEDICO INT NOT NULL,
    PERMISO BOOLEAN NOT NULL DEFAULT FALSE,
    FECHA_AUTORIZACION DATETIME DEFAULT CURRENT_TIMESTAMP,

    UNIQUE (ID_USUARIO, ID_MEDICO),

    FOREIGN KEY (ID_USUARIO)
        REFERENCES Usuario(ID_USUARIO)
        ON DELETE RESTRICT,

    FOREIGN KEY (ID_MEDICO)
        REFERENCES Medico(ID_MEDICO)
        ON DELETE RESTRICT
) ENGINE=InnoDB;

-- 7. AUTENTICACION
CREATE TABLE IF NOT EXISTS Autenticacion (
    ID_AUTH INT AUTO_INCREMENT PRIMARY KEY,
    ID_USUARIO INT NOT NULL UNIQUE,
    ULTIMO_LOGIN DATETIME NULL,
    INTENTOS_FALLIDOS INT NOT NULL DEFAULT 0,
    BLOQUEADO BOOLEAN NOT NULL DEFAULT FALSE,

    FOREIGN KEY (ID_USUARIO)
        REFERENCES Usuario(ID_USUARIO)
        ON DELETE CASCADE
) ENGINE=InnoDB;

-- 8. OTP
CREATE TABLE IF NOT EXISTS OTP (
    ID_OTP INT AUTO_INCREMENT PRIMARY KEY,
    ID_USUARIO INT NOT NULL,
    CODIGO VARCHAR(255) NOT NULL,
    FECHA_EXPIRACION DATETIME NOT NULL,
    USADO BOOLEAN NOT NULL DEFAULT FALSE,

    FOREIGN KEY (ID_USUARIO)
        REFERENCES Usuario(ID_USUARIO)
        ON DELETE CASCADE
) ENGINE=InnoDB;

-- 9. SESION
CREATE TABLE IF NOT EXISTS Sesion (
    ID_SESION INT AUTO_INCREMENT PRIMARY KEY,
    ID_USUARIO INT NOT NULL,
    TOKEN VARCHAR(255) NOT NULL,
    FECHA_INICIO DATETIME DEFAULT CURRENT_TIMESTAMP,
    FECHA_FIN DATETIME NULL,

    FOREIGN KEY (ID_USUARIO)
        REFERENCES Usuario(ID_USUARIO)
        ON DELETE CASCADE
) ENGINE=InnoDB;

-- 10. AUDITORIA
CREATE TABLE IF NOT EXISTS Auditoria (
    ID_AUDITORIA INT AUTO_INCREMENT PRIMARY KEY,
    ID_USUARIO INT NOT NULL,
    ACCION VARCHAR(255) NOT NULL,
    FECHA DATETIME DEFAULT CURRENT_TIMESTAMP,
    IP VARCHAR(45),

    FOREIGN KEY (ID_USUARIO)
        REFERENCES Usuario(ID_USUARIO)
        ON DELETE RESTRICT
) ENGINE=InnoDB;
